from pathlib import Path
from playwright.sync_api import sync_playwright
A=Path(__file__).resolve().parents[1]
ERR=[]
with sync_playwright() as p:
  b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
  page=b.new_page(viewport={'width':1540,'height':940},accept_downloads=True)
  page.on('pageerror',lambda e:ERR.append(str(e)))
  page.set_default_timeout(7000)
  page.on('dialog',lambda d:d.accept())
  html=(A/'index.html').read_text()
  html=html.replace('<link rel="stylesheet" href="assets/desktop.css">','<style>'+(A/'assets/desktop.css').read_text()+'</style>')
  for filename in ('data/scenarios.js','data/practical_missions.js','core/engine.js','core/desktop.js'):
    html=html.replace(f'<script defer src="{filename}"></script>','')
  html=html.replace('</body>',''.join('<script>'+(A/filename).read_text()+'</script>' for filename in ('data/scenarios.js','data/practical_missions.js','core/engine.js','core/desktop.js'))+'</body>')
  page.set_content(html,wait_until='load')
  page.wait_for_timeout(400)
  print('TITLE',page.title())
  print('ROOT',page.locator('#root').inner_text()[:400])
  page.locator('.accept').evaluate_all('(els)=>els.forEach(x=>{x.checked=true;x.dispatchEvent(new Event("change",{bubbles:true}))})')
  assert page.locator('#accept').is_enabled()
  page.locator('#accept').click()
  page.wait_for_timeout(300)
  assert 'Your analyst shift' in page.locator('#win-brief').inner_text()
  print('INITIAL WINDOWS',page.locator('.window').count())
  page.screenshot(path='/mnt/data/northbridge_v3_preview.png',full_page=True)
  # close help and start investigation
  page.locator('#win-help [data-act="close"]').click()
  page.locator('[data-act="open"][data-app="siem"]').first.click()
  page.locator('#win-siem [data-act="inspect"]').first.click()
  assert 'Inspector' in page.locator('#win-siem').inner_text()
  page.locator('#win-siem [data-act="flag"]').click()
  page.locator('[data-act="open"][data-app="locker"]').first.click()
  page.locator('#win-locker [data-act="choose-evidence"]').first.click()
  page.locator('#win-locker #ev-purpose').fill('Correlate password attempts and sign-in outcome for first investigation.')
  page.locator('#win-locker [data-act="preserve"]').click()
  page.wait_for_timeout(300)
  print('LOCKER',page.locator('#win-locker').inner_text()[-600:])
  assert 'Preserved artefacts (1)' in page.locator('#win-locker').inner_text()
  page.locator('#win-locker [data-act="verify"]').click()
  print('VERIFY',page.locator('#win-locker').inner_text()[-300:])
  page.locator('[data-act="open"][data-app="terminal"]').first.click()
  page.locator('#terminal-input').fill('hosts')
  page.locator('#terminal-input').press('Enter')
  assert 'ID-01' in page.locator('#console-terminal').inner_text()
  page.locator('#terminal-input').fill('Get-WinEvent')
  page.locator('#terminal-input').press('Enter')
  assert 'ID-101' in page.locator('#console-terminal').inner_text()
  page.locator('[data-act="open"][data-app="response"]').first.click()
  page.locator('#win-response [data-filter="responseControl"]').select_option('block-ip')
  page.locator('#response-reason').fill('Block only suspicious external attempts after checking no successful hostile login; verify identity access afterwards.')
  page.locator('#win-response [data-act="apply-response"]').click()
  print('RESPONSE',page.locator('#win-response').inner_text()[-550:])
  assert 'targeted threat route is reduced' in page.locator('#win-response').inner_text()
  page.locator('[data-act="open"][data-app="notes"]').first.click()
  page.locator('#journal-knowns').fill('ID-101 shows a rejected sign-in from the external source; ID-103 demonstrates a policy block.')
  page.locator('#journal-advisory').fill('No confirmed successful suspicious login. Continue targeted controls and monitoring. Check validated access for affected user.')
  page.locator('#win-notes [data-act="report"]').click()
  with page.expect_download() as d:page.locator('#win-notes [data-act="report"]').click()
  d.value.save_as('/mnt/data/northbridge_v3_test_report.html')
  assert 'ID-101' in Path('/mnt/data/northbridge_v3_test_report.html').read_text()
  # Check move mission
  page.locator('[data-act="case-picker"]').click()
  page.locator('[data-act="choose-case"][data-id="lockdown"]').click()
  page.locator('[data-act="open"][data-app="endpoint"]').first.click()
  page.locator('#win-endpoint [data-filter="endpointHost"]').select_option('FIN-WS-07')
  page.locator('#win-endpoint [data-act="inspect"][data-id="PROC-FIN-WS-07-4310"]').click()
  page.locator('#win-endpoint [data-act="flag"]').click()
  page.locator('[data-act="open"][data-app="response"]').first.click()
  page.locator('#win-response [data-filter="responseControl"]').select_option('isolate')
  page.locator('#win-response [data-filter="responseAsset"]').select_option('FIN-WS-07')
  page.locator('#response-reason').fill('ED-302 indicates active file encryption; isolate FIN-WS-07 to protect the shared file service, preserve triage evidence first where practical.')
  page.locator('#win-response [data-act="apply-response"]').click()
  page.locator('[data-act="open"][data-app="network"]').first.click()
  assert 'BLOCKED' in page.locator('#win-network').inner_text()
  page.screenshot(path='/mnt/data/northbridge_v3_workbench.png',full_page=True)
  page.locator('[data-act="open"][data-app="recovery"]').first.click()
  for i in range(3):page.locator(f'#win-recovery [data-recovery-check="{i}"]').check()
  page.locator('#recovery-reason').fill('Use protected 08:00 backup after test and monitored staged recovery with service owner sign-off.')
  page.locator('#win-recovery [data-act="apply-recovery"]').click()
  assert 'sandbox validation' in page.locator('#win-recovery').inner_text()
  # Reset one tool and prove another retained
  page.locator('[data-act="restore"][data-app="endpoint"]').click()
  page.locator('#win-endpoint [data-act="reset-tool"]').click()
  page.locator('#overlay-host [data-act="confirm"]').click()
  page.locator('#win-network').wait_for()
  assert 'BLOCKED' in page.locator('#win-network').inner_text()
  # Northbridge release
  page.locator('[data-act="case-picker"]').click()
  page.locator('[data-act="choose-case"][data-id="northbridge"]').click()
  for i in range(4):page.locator('#win-brief [data-act="advance"]').click()
  page.locator('[data-act="open"][data-app="siem"]').first.click()
  assert 'FW-402' in page.locator('#win-siem').inner_text()
  page.set_viewport_size({'width':430,'height':840})
  page.screenshot(path='/mnt/data/northbridge_v3_mobile.png',full_page=True)
  print('ERRORS',ERR)
  assert not ERR,ERR
  b.close()
print('V3 QA PASS')
